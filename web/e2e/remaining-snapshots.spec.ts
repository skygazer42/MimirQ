import { test, expect } from '@playwright/test'
import { snapshotFixture, snapshotRoute } from './remaining-snapshots.helpers'
import { openRemaining, remainingShot } from './remaining-pages.helpers'

test('snapshot comparison uses real-shaped changes, paging, detail and original content', async ({ page }) => {
  const state = await snapshotFixture(page)
  await openRemaining(page, snapshotRoute, '图谱快照')
  const start = page.getByRole('button', { name: '开始对比', exact: true })
  await expect(start).toBeEnabled()
  await expect(page.getByRole('table', { name: '快照变更明细' })).toHaveCount(0)
  expect(state.graphReads).toBe(0)
  await start.click()
  const table = page.getByRole('table', { name: '快照变更明细' })
  await expect(table.getByRole('row')).toHaveCount(21)
  await remainingShot(page, 'after-graph-snapshots-filled')
  await page.getByRole('button', { name: '下一页变更' }).click()
  await expect(table.getByRole('row')).toHaveCount(8)
  await page.getByRole('button', { name: '查看变更 设备手册', exact: true }).click()
  await expect(page.getByRole('dialog').locator('pre')).toContainText('12个月')
  await expect(page.getByRole('dialog').locator('pre')).toContainText('6个月')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '原始对照', exact: true }).click()
  await expect(page.getByText('"version-a"', { exact: true }).first()).toBeVisible()
  await remainingShot(page, 'after-graph-snapshots-raw')
  await page.getByRole('tab', { name: '图谱预览', exact: true }).click()
  const node = page.getByRole('button', { name: '选择节点 设备手册', exact: true })
  await expect(node).toBeVisible()
  await expect(page.getByRole('heading', { name: '节点详情', exact: true })).toHaveCount(0)
  await node.click()
  await expect(page.getByRole('heading', { name: '节点详情', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '收起节点详情', exact: true }).click()
  await expect(page.getByRole('heading', { name: '节点详情', exact: true })).toHaveCount(0)
  await remainingShot(page, 'after-graph-snapshots-graph')
  expect(state.diffs).toHaveLength(1)
})

test('snapshot failure retains scope, and phone node details close back to the graph', async ({ page }) => {
  const state = await snapshotFixture(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await openRemaining(page, snapshotRoute, '图谱快照')
  await page.getByRole('button', { name: '版本与范围', exact: true }).click()
  const scope = page.getByRole('dialog')
  await expect(scope.getByRole('combobox', { name: '快照 A', exact: true })).toHaveValue('version-a')
  await expect(scope.getByRole('combobox', { name: '快照 B', exact: true })).toHaveValue('version-b')
  const doc = '44444444-4444-4444-8444-444444444444'
  await scope.getByRole('textbox', { name: '文档范围（选填）', exact: true }).fill(doc)
  state.failCompare = true
  await scope.getByRole('button', { name: '开始对比', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '快照对比暂不可用' })).toBeVisible()
  await page.getByRole('button', { name: '版本与范围', exact: true }).click()
  await expect(scope.getByRole('textbox', { name: '文档范围（选填）', exact: true })).toHaveValue(doc)
  await scope.getByRole('button', { name: '完成', exact: true }).click()
  state.failCompare = false
  await page.getByRole('button', { name: '开始对比', exact: true }).click()
  await expect(page.getByRole('table', { name: '快照变更明细' })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await remainingShot(page, 'after-graph-snapshots-phone')
  await page.getByRole('tab', { name: '图谱预览', exact: true }).click()
  const node = page.getByRole('button', { name: '选择节点 设备手册', exact: true })
  await expect(node).toBeVisible()
  await node.click()
  await expect(page.getByRole('dialog', { name: '节点详情', exact: true })).toBeVisible()
  await remainingShot(page, 'after-graph-snapshots-node-phone')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(node).toBeFocused()
  state.failGraph = true
  await page.getByRole('button', { name: '重新读取图谱', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '预览图谱暂不可用' })).toBeVisible()
  await expect(page.getByTestId('kg-snapshot-graph-canvas')).toHaveCount(0)
  expect(state.exports.some(query => query.includes(doc))).toBeTruthy()
})

test('summary-only comparison retains real deltas and does not fabricate snapshot totals', async ({ page }) => {
  const state = await snapshotFixture(page)
  await openRemaining(page, snapshotRoute, '图谱快照')
  await page.getByRole('button', { name: '版本与范围', exact: true }).click()
  const response = page.waitForResponse(value => new URL(value.url()).pathname === '/api/v1/kg/snapshots/compare' && value.ok())
  await page.getByRole('dialog').getByRole('button', { name: '仅比较摘要', exact: true }).click()
  await response
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('tab', { name: /统计/ }).click()
  await expect(page.getByRole('cell', { name: '未取得', exact: true })).toHaveCount(10)
  expect(state.exports).toHaveLength(0)
  await page.getByRole('button', { name: '读取完整快照', exact: true }).click()
  await expect.poll(() => state.exports.length).toBe(2)
  await expect(page.getByRole('cell', { name: '未取得', exact: true })).toHaveCount(0)
})

test('snapshot comparison remains readable in a narrow dark workspace', async ({ page }) => {
  await snapshotFixture(page, 'dark')
  await page.setViewportSize({ width: 1120, height: 850 })
  await openRemaining(page, snapshotRoute, '图谱快照')
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.getByRole('button', { name: '开始对比', exact: true }).click()
  await expect(page.getByRole('table', { name: '快照变更明细' }).getByRole('row')).toHaveCount(21)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await expect(page.getByText('已生成对比结果', { exact: true })).toHaveCount(0, { timeout: 10000 })
  await remainingShot(page, 'after-graph-snapshots-narrow-dark')
})
