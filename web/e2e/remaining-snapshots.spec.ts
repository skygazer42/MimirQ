import { test, expect } from '@playwright/test'
import { snapshotFixture, snapshotRoute } from './remaining-snapshots.helpers'
import { openRemaining, remainingShot } from './remaining-pages.helpers'

test('snapshot comparison uses real-shaped changes, paging, detail and original content', async ({ page }) => {
  const state = await snapshotFixture(page)
  await openRemaining(page, snapshotRoute, '图谱快照')
  const start = page.getByRole('button', { name: '开始对比', exact: true })
  await expect(start).toBeEnabled()
  await expect(page.getByRole('table', { name: '快照变更明细' })).toHaveCount(0)
  await remainingShot(page, 'after-graph-snapshots-empty')
  expect(state.graphReads).toBe(0)
  await start.click()
  const table = page.getByRole('table', { name: '快照变更明细' })
  await expect(table.getByRole('row')).toHaveCount(21)
  await expect(page.getByText('已生成对比结果', { exact: true })).toHaveCount(0, { timeout: 10000 })
  await remainingShot(page, 'after-graph-snapshots-filled')
  await expect(page.getByRole('button', { name: '任务中心', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '下一页变更' }).click()
  await expect(table.getByRole('row')).toHaveCount(8)
  await page.getByRole('button', { name: '查看变更 设备手册', exact: true }).click()
  const properties = page.getByRole('table', { name: '变更属性对照', exact: true })
  await expect(properties.getByRole('rowheader', { name: '维护周期', exact: true })).toBeVisible()
  await expect(properties.getByRole('cell', { name: '12个月', exact: true })).toBeVisible()
  await expect(properties.getByRole('cell', { name: '6个月', exact: true })).toBeVisible()
  await remainingShot(page, 'after-graph-snapshots-change-detail')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '原始对照', exact: true }).click()
  await expect(page.getByText('"version-a"', { exact: true }).first()).toBeVisible()
  await remainingShot(page, 'after-graph-snapshots-raw')
  await page.getByRole('tab', { name: '快照 A', exact: true }).click()
  await expect(page.getByRole('button', { name: '复制 JSON', exact: true })).toBeEnabled()
  await remainingShot(page, 'after-graph-snapshots-a')
  await page.getByRole('tab', { name: '快照 B', exact: true }).click()
  await expect(page.getByRole('button', { name: '导出 JSON', exact: true })).toBeEnabled()
  await page.getByRole('tab', { name: '统计', exact: true }).click()
  await remainingShot(page, 'after-graph-snapshots-stats')
  await page.getByRole('tab', { name: '图谱预览', exact: true }).click()
  const node = page.getByRole('button', { name: '选择节点 设备手册', exact: true })
  await expect(node).toBeVisible()
  const deviceColor = await node
    .locator(':scope > span')
    .first()
    .evaluate((element) => getComputedStyle(element).backgroundColor)
  const conceptColor = await page
    .getByRole('button', { name: '选择节点 维护条目 01', exact: true })
    .locator(':scope > span')
    .first()
    .evaluate((element) => getComputedStyle(element).backgroundColor)
  expect(deviceColor).not.toBe(conceptColor)
  await expect(page.getByRole('heading', { name: '节点详情', exact: true })).toHaveCount(0)
  await node.click()
  await expect(page.getByRole('heading', { name: '节点详情', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '收起节点详情', exact: true }).click()
  await expect(page.getByRole('heading', { name: '节点详情', exact: true })).toHaveCount(0)
  await remainingShot(page, 'after-graph-snapshots-graph')
  await page.getByRole('button', { name: '版本与范围', exact: true }).click()
  await page.getByRole('button', { name: '清空快照对比', exact: true }).click()
  await expect(page.getByRole('heading', { name: '还没有对比结果', exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: '快照变更明细' })).toHaveCount(0)
  expect(state.diffs).toHaveLength(1)
})

test('snapshot failure retains scope, and phone node details close back to the graph', async ({ page }) => {
  const state = await snapshotFixture(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await openRemaining(page, snapshotRoute, '图谱快照')
  const titleBox = await page.getByRole('heading', { name: '图谱快照', exact: true }).boundingBox()
  const actionBox = await page.getByRole('button', { name: '开始对比', exact: true }).boundingBox()
  expect(Math.abs(titleBox!.y + titleBox!.height / 2 - actionBox!.y - actionBox!.height / 2)).toBeLessThan(
    actionBox!.height,
  )
  await page.getByRole('button', { name: '版本与范围', exact: true }).click()
  const scope = page.getByRole('dialog')
  await expect(scope.getByRole('combobox', { name: '快照 A', exact: true })).toHaveValue('version-a')
  await expect(scope.getByRole('combobox', { name: '快照 B', exact: true })).toHaveValue('version-b')
  await remainingShot(page, 'after-graph-snapshots-scope-phone')
  const doc = '44444444-4444-4444-8444-444444444444'
  await scope.getByRole('textbox', { name: '文档范围（选填）', exact: true }).fill(doc)
  state.failCompare = true
  await scope.getByRole('button', { name: '开始对比', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '快照对比暂不可用' })).toBeVisible()
  await expect(page.getByText('版本已就绪，可开始对比', { exact: true })).toHaveCount(0)
  await remainingShot(page, 'after-graph-snapshots-error-phone')
  await page.getByRole('button', { name: '版本与范围', exact: true }).click()
  await expect(scope.getByRole('textbox', { name: '文档范围（选填）', exact: true })).toHaveValue(doc)
  await scope.getByRole('button', { name: '完成', exact: true }).click()
  state.failCompare = false
  await page.getByRole('button', { name: '开始对比', exact: true }).click()
  const table = page.getByRole('table', { name: '快照变更明细' })
  await expect(table).toBeVisible()
  const tools = page.getByRole('button', { name: '筛选与视图', exact: true })
  await expect(tools).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('textbox', { name: '搜索变更对象', exact: true })).toBeHidden()
  await expect(page.getByText('已生成对比结果', { exact: true })).toHaveCount(0, { timeout: 10000 })
  expect((await table.locator('thead').boundingBox())!.y).toBeLessThan(250)
  for (const target of [tools, page.getByRole('button', { name: '开始对比', exact: true })]) {
    const box = (await target.boundingBox())!
    expect(box.height).toBeGreaterThanOrEqual(44)
    expect(box.width).toBeGreaterThanOrEqual(44)
  }
  await tools.click()
  await page.getByRole('combobox', { name: '变更类型', exact: true }).selectOption('更新')
  await expect(table.getByRole('row')).toHaveCount(2)
  await page.getByRole('button', { name: '原始对照', exact: true }).click()
  await tools.click()
  await expect(page.getByRole('region', { name: '快照原始对照', exact: true })).toBeVisible()
  await tools.click()
  await page.getByRole('button', { name: '变更明细', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '变更类型', exact: true })).toHaveValue('更新')
  await page.getByRole('combobox', { name: '变更类型', exact: true }).selectOption('全部')
  await tools.click()
  await expect(table.getByRole('row')).toHaveCount(21)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await remainingShot(page, 'after-graph-snapshots-phone')
  await page.getByRole('tab', { name: '统计', exact: true }).click()
  await remainingShot(page, 'after-graph-snapshots-stats-phone')
  await page.getByRole('tab', { name: '图谱预览', exact: true }).click()
  const node = page.getByRole('button', { name: '选择节点 设备手册', exact: true })
  await expect(node).toBeVisible()
  await node.click()
  await expect(page.getByRole('dialog', { name: '节点详情', exact: true })).toBeVisible()
  await remainingShot(page, 'after-graph-snapshots-node-phone')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(node).toBeFocused()
  await remainingShot(page, 'after-graph-snapshots-graph-phone')
  state.failGraph = true
  await page.getByRole('button', { name: '重新读取图谱', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '预览图谱暂不可用' })).toBeVisible()
  await expect(page.getByTestId('kg-snapshot-graph-canvas')).toHaveCount(0)
  expect(state.exports.some((query) => query.includes(doc))).toBeTruthy()
})

test('snapshot comparison announces pending work before a result exists', async ({ page }) => {
  const state = await snapshotFixture(page)
  await page.setViewportSize({ width: 390, height: 844 })
  let release!: () => void
  state.gate = new Promise<void>((resolve) => {
    release = resolve
  })
  await openRemaining(page, snapshotRoute, '图谱快照')
  await page.getByRole('button', { name: '开始对比', exact: true }).click()
  try {
    await expect.poll(() => state.diffs.length).toBe(1)
    await expect(page.getByRole('status').filter({ hasText: '正在读取快照并生成对比' })).toBeVisible()
    await expect(page.getByRole('heading', { name: '还没有对比结果', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '正在对比…', exact: true })).toBeDisabled()
    await remainingShot(page, 'after-graph-snapshots-pending-phone')
  } finally {
    release()
  }
  await expect(page.getByRole('table', { name: '快照变更明细' })).toBeVisible()
})

test('summary-only comparison retains real deltas and does not fabricate snapshot totals', async ({ page }) => {
  const state = await snapshotFixture(page)
  await openRemaining(page, snapshotRoute, '图谱快照')
  await page.getByRole('button', { name: '版本与范围', exact: true }).click()
  const response = page.waitForResponse(
    (value) => new URL(value.url()).pathname === '/api/v1/kg/snapshots/compare' && value.ok(),
  )
  await page.getByRole('dialog').getByRole('button', { name: '仅比较摘要', exact: true }).click()
  await response
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('tab', { name: /统计/ }).click()
  await expect(page.getByRole('cell', { name: '未取得', exact: true })).toHaveCount(10)
  expect(state.exports).toHaveLength(0)
  await page.getByRole('button', { name: '读取完整快照', exact: true }).click()
  await expect.poll(() => state.exports.length).toBe(2)
  await expect(page.getByRole('cell', { name: '未取得', exact: true })).toHaveCount(0)
})

