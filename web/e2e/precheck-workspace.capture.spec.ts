import { test, expect } from '@playwright/test'
import { openPrecheck, precheckFixture, precheckShot } from './precheck-workspace.helpers'

test('capture current dark report with warning states', async ({ page }) => {
  await precheckFixture(page, 'dark')
  await openPrecheck(page)
  await expect(page.locator('[data-precheck-total]')).toBeVisible({ timeout: 30000 })
  await expect(page.locator('.recharts-pie-sector').first()).toBeVisible()
  await precheckShot(page, 'after-desktop-dark')
})

test('capture completed report, configuration and narrow states', async ({ page }) => {
  await precheckFixture(page)
  await openPrecheck(page)
  await expect(page.locator('[data-precheck-total]')).toBeVisible({ timeout: 30000 })
  await expect(page.locator('.recharts-pie-sector').first()).toBeVisible()
  await precheckShot(page, 'after-desktop')
  const report = page.getByRole('tabpanel', { name: '质量报告' })
  await report.getByText('密钥命中（次数）', { exact: true }).scrollIntoViewIfNeeded()
  await precheckShot(page, 'report-lower-desktop')
  await page.getByRole('tab', { name: '样本与近重复', exact: true }).click()
  await page.getByRole('button', { name: '加载', exact: true }).nth(0).click()
  await expect(page.getByRole('table', { name: '预检代表性样本' })).toBeVisible()
  await precheckShot(page, 'samples-desktop')
  await page.getByRole('button', { name: '新建预检', exact: true }).click()
  await precheckShot(page, 'config-desktop')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '生成策略', exact: true }).click()
  await expect(page.getByRole('heading', { name: /建议规则.*4/ })).toBeVisible()
  await precheckShot(page, 'policy-desktop')
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.locator('[data-precheck-total]')).toBeVisible({ timeout: 60000 })
  await page.locator('[data-precheck-total]').scrollIntoViewIfNeeded()
  await precheckShot(page, 'after-phone')
  await page.getByRole('button', { name: '新建预检', exact: true }).click()
  await precheckShot(page, 'config-phone')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '生成策略', exact: true }).click()
  await expect(page.getByRole('heading', { name: /建议规则.*4/ })).toBeVisible()
  await precheckShot(page, 'policy-phone')
})
