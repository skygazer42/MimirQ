test('saving keeps a failed draft and raw comma input, then persists create and edit',async({page})=>{
  const state=await promptFixture(page);await openPrompts(page)
  await page.getByRole('button',{name:'创建模板',exact:true}).click()
  const form=page.getByRole('dialog',{name:'创建模板',exact:true})
  await form.getByLabel('模板名称',{exact:true}).fill('保存流程核对')
  await form.getByLabel('模板正文',{exact:true}).fill('请根据 {context} 回答 {question}。')
  await form.getByLabel(/^变量/).pressSequentially('context, question, history')
  await form.getByLabel(/^标签/).fill('技术, 中文, 技术')
  await expect(form.getByLabel(/^变量/)).toHaveValue('context, question, history')
  state.failSave=true
  await form.getByRole('button',{name:'保存模板',exact:true}).click()
  await expect(form.getByRole('alert')).toContainText('模板暂时无法保存')
  await expect(form.getByLabel('模板名称',{exact:true})).toHaveValue('保存流程核对')
  state.failSave=false
  let release=()=>{}
  state.saveGate=new Promise<void>(resolve=>{release=resolve})
  try {
    await form.getByRole('button',{name:'保存模板',exact:true}).click()
    await expect(form.getByRole('button',{name:'保存中',exact:true})).toBeDisabled()
    await expect.poll(()=>state.writes.length).toBe(2)
  } finally {release();state.saveGate=null}
  await expect(form).toBeHidden()
  const created=state.items.find(t=>t.name==='保存流程核对')!
  expect(created.variables).toEqual(['context','question','history']);expect(created.tags).toEqual(['技术','中文'])
  await reloadPrompts(page);await expect(page.getByRole('table',{name:'提示词模板'})).toContainText('保存流程核对')
  await page.getByRole('button',{name:'更多操作 保存流程核对',exact:true}).click()
  await page.getByRole('menuitem',{name:'编辑模板',exact:true}).click()
  const edit=page.getByRole('dialog',{name:'编辑模板',exact:true})
  await expect(edit.getByLabel('模板名称',{exact:true})).toBeFocused()
  await edit.getByLabel(/^用途说明/).fill('更新后的用途')
  await edit.getByRole('switch',{name:'启用模板',exact:true}).click()
  await edit.getByRole('button',{name:'保存模板',exact:true}).click()
  await expect(edit).toBeHidden()
  await reloadPrompts(page)
  const row=page.getByRole('row').filter({hasText:'保存流程核对'})
  await expect(row).toContainText('更新后的用途');await expect(row).toContainText('停用')
  expect(state.errors).toEqual([])
})

test('bulk partial failures retain only failed selections and failed deletion remains recoverable',async({page})=>{
  const state=await promptFixture(page),first=state.items.find(t=>!t.is_system)!
  state.items.push({...first,id:'custom-two',name:'运维文档问答'})
  await openPrompts(page);await choose(page,'模板来源','自定义模板')
  await page.getByRole('checkbox',{name:'选择本页自定义模板',exact:true}).check()
  state.failId='custom-two'
  await page.getByRole('button',{name:'批量停用',exact:true}).click()
  await expect(page.locator('[data-prompts-workbench]').getByRole('alert')).toContainText('1 个模板未停用')
  await expect(page.getByRole('checkbox',{name:'选择 运维文档问答',exact:true})).toBeChecked()
  await expect(page.getByRole('checkbox',{name:`选择 ${first.name}`,exact:true})).not.toBeChecked()
  await expect(page.getByText('已选择 1 个模板',{exact:true})).toBeVisible()
  state.failId=''
  await page.getByRole('button',{name:'批量停用',exact:true}).click()
  await expect(page.getByText('已选择 1 个模板',{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'更多操作 运维文档问答',exact:true}).click()
  await page.getByRole('menuitem',{name:'删除模板',exact:true}).click()
  const confirm=page.getByRole('alertdialog')
  state.failId='custom-two'
  await confirm.getByRole('button',{name:'删除模板',exact:true}).click()
  await expect(confirm.getByRole('alert')).toContainText('未删除')
  await expect(confirm).toContainText('运维文档问答')
  state.failId=''
  await confirm.getByRole('button',{name:'删除模板',exact:true}).click()
  await expect(confirm).toBeHidden()
  await expect(page.getByRole('table',{name:'提示词模板'})).not.toContainText('运维文档问答')
  await expect(page.getByRole('button',{name:'创建模板',exact:true})).toBeFocused()
  expect(state.writes.every(w=>!state.items.find(t=>t.id===w.path.split('/')[4])?.is_system)).toBe(true)
  expect(state.errors).toEqual([])
})

