import fs from 'node:fs'
import path from 'node:path'
import { test, expect } from '@playwright/test'
import { memberFixture, openMembers, reloadMembers } from './members-table.helpers'

const evidence = path.resolve(__dirname, '../../artifacts/rebrand/members-table-v1/ux-review')
test('independent open UX observation', async ({ page }) => {
  fs.mkdirSync(evidence, { recursive: true })
  const state = await memberFixture(page)
  await openMembers(page)
  await page.screenshot({ path: path.join(evidence, '01-desktop-entry.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '角色说明', exact: true }).click()
  console.log('ROLE_HELP', await page.locator('body').ariaSnapshot())
  await page.screenshot({ path: path.join(evidence, '02-role-help.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.getByRole('searchbox', { name: '搜索成员' }).fill('顾言')
  await expect(page.getByRole('combobox', { name: '角色 顾言', exact: true })).toBeVisible()
  await page.screenshot({ path: path.join(evidence, '03-found-member.png'), animations: 'disabled' })
  await page.getByRole('combobox', { name: '角色 顾言', exact: true }).click()
  console.log('ROLE_OPTIONS', await page.locator('body').ariaSnapshot())
  await page.getByRole('option', { name: '编辑者', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '角色 顾言', exact: true })).toContainText('编辑者')
  expect(state.members.find(member => member.user_id === 'member-viewer-b')?.role).toBe('editor')
  await page.screenshot({ path: path.join(evidence, '04-after-role-selection.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '刷新成员', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '角色 顾言', exact: true })).toContainText('编辑者')
  await expect(page.getByRole('searchbox', { name: '搜索成员' })).toHaveValue('顾言')
  await reloadMembers(page)
  console.log('AFTER_RELOAD_SEARCH', await page.getByRole('searchbox', { name: '搜索成员' }).inputValue())
  await page.getByRole('searchbox', { name: '搜索成员' }).fill('顾言')
  await expect(page.getByRole('combobox', { name: '角色 顾言', exact: true })).toContainText('编辑者')
  await page.screenshot({ path: path.join(evidence, '05-desktop-reload-confirmed.png'), animations: 'disabled' })

  // Chosen risk: a rejected attempt to revert a saved role must preserve the confirmed result and search context.
  await page.getByRole('combobox', { name: '筛选角色', exact: true }).click()
  await page.getByRole('option', { name: '编辑者', exact: true }).click()
  state.failRole = '租户策略拒绝这次角色变更'
  await page.getByRole('combobox', { name: '角色 顾言', exact: true }).click()
  await page.getByRole('option', { name: '查看者', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '租户策略拒绝这次角色变更' })).toBeVisible()
  console.log('AFTER_REJECTED_ROLE_CHANGE', await page.locator('body').ariaSnapshot())
  await page.screenshot({ path: path.join(evidence, '06-desktop-rejected-role.png'), animations: 'disabled' })
  await expect(page.getByRole('combobox', { name: '角色 顾言', exact: true })).toContainText('编辑者')
  await expect(page.getByRole('searchbox', { name: '搜索成员' })).toHaveValue('顾言')
  expect(state.members.find(member => member.user_id === 'member-viewer-b')?.role).toBe('editor')
  console.log('FIXTURE_WRITES', JSON.stringify(state.writes))
  console.log('FIXTURE_ERRORS', JSON.stringify(state.errors))
  fs.writeFileSync(path.join(evidence, 'desktop-state.json'), JSON.stringify({ writes: state.writes, reads: state.reads, blocked: state.blocked, errors: state.errors, savedRole: state.members.find(member => member.user_id === 'member-viewer-b')?.role, snapshot: await page.locator('body').ariaSnapshot() }, null, 2))
  expect(state.blocked).toEqual([])
})

