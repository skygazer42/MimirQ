test('adding members preserves failure choices, locks pending inputs and supports remove with undo',async({page})=>{
  const state=await groupFixture(page);await openGroups(page)
  await page.getByRole('button',{name:'添加成员',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'添加成员',exact:true})
  await dialog.getByRole('searchbox',{name:'搜索可添加成员',exact:true}).fill('季禾')
  await dialog.getByRole('checkbox',{name:'选择 季禾',exact:true}).check()
  state.failAdd=true;await dialog.getByRole('button',{name:'添加成员',exact:true}).click()
  await expect(dialog.getByRole('alert')).toContainText('成员暂时无法添加')
  await expect(dialog.getByRole('checkbox',{name:'选择 季禾',exact:true})).toBeChecked()
  state.failAdd=false;let release=()=>{};state.saveGate=new Promise<void>(resolve=>{release=resolve})
  try{
    await dialog.getByRole('button',{name:'添加成员',exact:true}).click()
    await expect(dialog.getByRole('button',{name:'添加中',exact:true})).toBeDisabled()
    await expect(dialog.getByRole('searchbox',{name:'搜索可添加成员',exact:true})).toBeDisabled()
    expect(state.writes.filter(item=>item.path.endsWith('/members'))).toHaveLength(2)
  }finally{release();state.saveGate=null}
  await expect(dialog).toHaveCount(0);await expect(memberArea(page)).toContainText('季禾')
  await page.getByRole('button',{name:'成员操作 季禾',exact:true}).click()
  await page.getByRole('menuitem',{name:'从组中移除',exact:true}).click()
  await expect(memberArea(page).getByRole('rowheader').filter({hasText:'季禾'})).toHaveCount(0)
  await page.getByRole('button',{name:'撤销',exact:true}).click()
  await expect(memberArea(page)).toContainText('季禾')
  await reloadGroups(page);await expect(memberArea(page)).toContainText('季禾')
  expect(state.writes.filter(item=>item.path.includes('/members')).every(item=>item.path.includes(selectedGroupId))).toBe(true)
  expect(state.errors).toEqual([]);expect(state.blocked).toEqual([])
})

