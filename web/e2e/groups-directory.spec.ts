test('empty, dark and 200-percent-equivalent views keep the workspace readable',async({browser})=>{
  for(const view of [{name:'empty-desktop',width:1600,height:1000,scale:1,theme:'light' as const,empty:true},{name:'desktop-dark',width:1600,height:1000,scale:1,theme:'dark' as const,empty:false},{name:'zoom-equivalent',width:800,height:500,scale:2,theme:'light' as const,empty:false},{name:'phone-light-320',width:320,height:844,scale:1,theme:'light' as const,empty:false}]){
    const context=await browser.newContext({baseURL:`http://127.0.0.1:${process.env.PLAYWRIGHT_PORT||3100}`,viewport:{width:view.width,height:view.height},deviceScaleFactor:view.scale})
    try{
      const page=await context.newPage(),state=await groupFixture(page,view.theme)
      if(view.empty)state.groups=[]
      await page.setViewportSize({width:view.width,height:view.height});await openGroups(page,view.empty?'/settings/groups':undefined)
      await expect(page.getByRole('button',{name:'新建组',exact:true})).toBeInViewport()
      if(view.empty)await expect(page.getByRole('heading',{name:'还没有组',exact:true})).toBeVisible()
      else await expect(detail(page)).toBeVisible()
      expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
      await shot(page,view.name)
      expect(state.errors).toEqual([]);expect(state.writes).toEqual([])
    }finally{await context.close()}
  }
})

