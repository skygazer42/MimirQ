import {groupFixture,openGroups,reloadGroups,selectedGroupId,evidence} from './groups-directory.helpers'

const detail=(page:Page,name='检索研发')=>page.getByRole('region',{name:`组详情 ${name}`,exact:true})
const memberArea=(page:Page,name='检索研发')=>page.getByRole('region',{name:`组成员 ${name}`,exact:true})
async function shot(page:Page,name:string){fs.mkdirSync(evidence,{recursive:true});await page.screenshot({path:`${evidence}/${name}.png`})}

